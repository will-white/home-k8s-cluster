#!/usr/bin/env python3
"""Generate one-piece-canon.txt for Kometa's `text_file` playlist builder.

Replaces the Trakt list Kometa used until 2.5.0 removed Trakt support. Edit the
ranges below when animefillerlist.com classifies new episodes, then run:

    python3 generate-one-piece-canon.py > one-piece-canon.txt

Source: https://www.animefillerlist.com/shows/one-piece (checked 2026-10-23,
episodes 1-1168 classified). "Canon" here = manga canon + anime canon + mixed
canon/filler; only pure filler is skipped.

Season/episode numbers must be the ones *Plex* uses, because Kometa resolves
each ID with show.episode(season=, episode=). Our "TV Shows" library uses the
Plex TV agent, i.e. TMDb's arc-based seasons (S1 = eps 1-8, S8 = the Warship
Island filler, ... 23 seasons as of 2026-10-23, read from the server). If the
library is ever switched to TVDb absolute order, run with --absolute.
"""
import argparse

# Kometa 2.5.3's text_file parser only accepts tvdb_episode:<id>_<S>_<E>. The
# TVDb ID is used only to find the show in the library; the season/episode are
# then looked up with Plex's own numbering (show.episode(season=, episode=)).
TVDB_ID = 81797  # One Piece on TheTVDB

FILLER = """54-60, 98-99, 102, 131-143, 196-206, 220-225, 279-283, 291-292, 303,
317-319, 326-336, 382-384, 406-407, 426-429, 457-458, 492, 542, 575-578, 590,
626-627, 747-750, 780-782, 895-896, 907, 1029-1030"""

LAST_CLASSIFIED = 1168

# Plex/TMDb numbering: season -> (first absolute episode, last absolute episode)
SEASONS = {
    1: (1, 8), 2: (9, 30), 3: (31, 47), 4: (48, 60), 5: (61, 69), 6: (70, 91),
    7: (92, 130), 8: (131, 143), 9: (144, 195), 10: (196, 226), 11: (227, 325),
    12: (326, 381), 13: (382, 481), 14: (482, 516), 15: (517, 578), 16: (579, 627),
    17: (628, 745), 18: (746, 778), 19: (779, 876), 20: (877, 890), 21: (891, 1084),
    22: (1085, 1154), 23: (1155, 1179),
}


def expand(ranges: str) -> set[int]:
    out: set[int] = set()
    for part in ranges.replace("\n", " ").split(","):
        part = part.strip()
        if not part:
            continue
        a, _, b = part.partition("-")
        out.update(range(int(a), int(b or a) + 1))
    return out


def season_of(absolute: int) -> tuple[int, int]:
    for season, (first, last) in SEASONS.items():
        if first <= absolute <= last:
            return season, absolute - first + 1
    raise SystemExit(f"episode {absolute} is outside the SEASONS table")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--absolute", action="store_true", help="emit absolute-order numbering (S1 E<abs>)")
    args = ap.parse_args()
    filler = expand(FILLER)
    print("# One Piece canon episodes (manga canon + anime canon + mixed; pure filler skipped).")
    print("# Generated by generate-one-piece-canon.py — do not edit by hand.")
    print(f"# Source: animefillerlist.com, episodes 1-{LAST_CLASSIFIED}; show = TVDb {TVDB_ID}, S/E = Plex (TMDb) numbering.")
    skipped_from = None
    for ep in range(1, LAST_CLASSIFIED + 1):
        if ep in filler:
            if skipped_from is None:
                skipped_from = ep
            continue
        if skipped_from is not None:
            end = ep - 1
            print(f"# filler {skipped_from}" + (f"-{end}" if end != skipped_from else ""))
            skipped_from = None
        if args.absolute:
            print(f"tvdb_episode:{TVDB_ID}_1_{ep}")
        else:
            s, e = season_of(ep)
            print(f"tvdb_episode:{TVDB_ID}_{s}_{e}  # ep {ep}")


if __name__ == "__main__":
    main()
